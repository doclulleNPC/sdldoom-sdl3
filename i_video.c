//
// I_ExpandFrame
// Expand the 8-bit palettized frame (screens[0]) into a 32-bit ARGB8888 image,
// compositing the truecolor 3D view wherever 2D (HUD/menu) didn't overdraw it.
// Shared by the SDL_Renderer (locked texture) and SDL_GPU (transfer buffer)
// presentation paths.  `pitch` is the destination row stride in bytes.
//
static void I_ExpandFrame (void* pixels, int pitch)
{
    int x, y;

    for (y=0 ; y<SCREENHEIGHT ; y++)
    {
	Uint32*		dst = (Uint32 *)((Uint8 *)pixels + y*pitch);
	unsigned char*	src = screens[0] + y*SCREENWIDTH;

	if (view_truecolor
	    && y >= viewwindowy && y < viewwindowy+viewheight)
	{
	    int		vx0 = viewwindowx;
	    int		vx1 = viewwindowx + scaledviewwidth;
	    Uint32*	s32  = screen32   + y*SCREENWIDTH;
	    byte*	snap = view8snap  + y*SCREENWIDTH;

	    for (x=0 ; x<SCREENWIDTH ; x++)
	    {
		if (x >= vx0 && x < vx1 && src[x] == snap[x])
		    dst[x] = s32[x];
		else
		    dst[x] = palette[src[x]];
	    }
	}
	else
	{
	    for (x=0 ; x<SCREENWIDTH ; x++)
		dst[x] = palette[src[x]];
	}
    }
}

