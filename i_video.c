//
// I_GpuConsole*
// The renderer path draws the drop-down console with SDL3's SDL_RenderDebugText
// (I_DrawConsole), which needs an SDL_Renderer the GPU path doesn't have.
// Reproduce it by blitting an 8x8 font (con_font8x8.h) straight into the
// expanded 32-bit frame.  Authored in BASE (320x200) coords and scaled by
// `hires` to match the renderer path's layout.  The dimmed backdrop is already
// in the 8-bit framebuffer (C_Drawer), so only the text is overlaid here.
//
static void I_GpuConsoleGlyph (Uint32* px, int bx, int by, unsigned char c, Uint32 col)
{
    const char*	g = font8x8_basic[c & 0x7f];
    int		gx, gy, sx, sy;

    for (gy=0 ; gy<8 ; gy++)
	for (gx=0 ; gx<8 ; gx++)
	{
	    if (!((g[gy] >> gx) & 1))	// bit 0 = leftmost column
		continue;
	    for (sy=0 ; sy<hires ; sy++)
	    {
		int py = (by+gy)*hires + sy;
		if (py < 0 || py >= SCREENHEIGHT) continue;
		for (sx=0 ; sx<hires ; sx++)
		{
		    int pxx = (bx+gx)*hires + sx;
		    if (pxx < 0 || pxx >= SCREENWIDTH) continue;
		    px[py*SCREENWIDTH + pxx] = col;
		}
	    }
	}
}

static void I_GpuConsoleText (Uint32* px, int bx, int by, const char* s, Uint32 col)
{
    for ( ; *s ; s++, bx += 6)
	I_GpuConsoleGlyph (px, bx, by, (unsigned char)*s, col);
}

static void I_GpuDrawConsole (Uint32* px)
{
    int			h, y, i;
    const Uint32	col = 0xffe0e0e0u;	// ARGB light grey

    h = C_BaseHeight ();
    if (h <= 0)
	return;

    y = h - 9;
    I_GpuConsoleText (px, 6, y, C_InputLine (), col);
    y -= 8;
    for (i = 0; i < C_ScrollCount () && y > -8; i++)
    {
	const char* line = C_ScrollLine (i);
	if (line && line[0])
	    I_GpuConsoleText (px, 6, y, line, col);
	y -= 8;
    }
}

//
// I_GpuDestroy
// Release every SDL_GPU object and the device itself.  Safe to call with a
// partially-built device (used both at shutdown and on init failure).
//
static void I_GpuDestroy (void)
{
    if (!gpu)
	return;
    if (gpu_pipeline)   SDL_ReleaseGPUGraphicsPipeline(gpu, gpu_pipeline);
    if (gpu_tex)        SDL_ReleaseGPUTexture(gpu, gpu_tex);
    if (gpu_xfer)       SDL_ReleaseGPUTransferBuffer(gpu, gpu_xfer);
    if (gpu_sampler_nn) SDL_ReleaseGPUSampler(gpu, gpu_sampler_nn);
    if (gpu_sampler_ln) SDL_ReleaseGPUSampler(gpu, gpu_sampler_ln);
    if (window)         SDL_ReleaseWindowFromGPUDevice(gpu, window);
    SDL_DestroyGPUDevice(gpu);
    gpu = NULL; gpu_pipeline = NULL; gpu_tex = NULL; gpu_xfer = NULL;
    gpu_sampler_nn = gpu_sampler_ln = NULL;
}

//
// I_GpuInit
// Create the GPU device, claim the window's swapchain, and build the blit
// pipeline + samplers.  Returns 0 on any failure (caller falls back to the
// SDL_Renderer path).
//
static int I_GpuInit (void)
{
    SDL_GPUShader*			vs;
    SDL_GPUShader*			fs;
    SDL_GPUShaderCreateInfo		sci;
    SDL_GPUGraphicsPipelineCreateInfo	pci;
    SDL_GPUColorTargetDescription	ctd;
    SDL_GPUSamplerCreateInfo		smp;

    gpu = SDL_CreateGPUDevice(SDL_GPU_SHADERFORMAT_SPIRV, false, NULL);
    if (!gpu)
    {
	fprintf(stderr, "I_GpuInit: no GPU device: %s\n", SDL_GetError());
	return 0;
    }
    if (!SDL_ClaimWindowForGPUDevice(gpu, window))
    {
	fprintf(stderr, "I_GpuInit: claim window: %s\n", SDL_GetError());
	SDL_DestroyGPUDevice(gpu); gpu = NULL;
	return 0;
    }

    SDL_zero(sci);
    sci.code = gpu_blit_vert_spv;	sci.code_size = gpu_blit_vert_spv_len;
    sci.entrypoint = "main";		sci.format = SDL_GPU_SHADERFORMAT_SPIRV;
    sci.stage = SDL_GPU_SHADERSTAGE_VERTEX;
    vs = SDL_CreateGPUShader(gpu, &sci);

    sci.code = gpu_blit_frag_spv;	sci.code_size = gpu_blit_frag_spv_len;
    sci.stage = SDL_GPU_SHADERSTAGE_FRAGMENT;
    sci.num_samplers = 1;		// one combined image sampler (set 2)
    fs = SDL_CreateGPUShader(gpu, &sci);

    if (!vs || !fs)
    {
	fprintf(stderr, "I_GpuInit: shader: %s\n", SDL_GetError());
	return 0;
    }

    SDL_zero(ctd);
    ctd.format = SDL_GetGPUSwapchainTextureFormat(gpu, window);

    SDL_zero(pci);
    pci.vertex_shader = vs;		pci.fragment_shader = fs;
    pci.primitive_type = SDL_GPU_PRIMITIVETYPE_TRIANGLELIST;
    pci.target_info.num_color_targets = 1;
    pci.target_info.color_target_descriptions = &ctd;
    gpu_pipeline = SDL_CreateGPUGraphicsPipeline(gpu, &pci);

    SDL_ReleaseGPUShader(gpu, vs);	// retained by the pipeline once built
    SDL_ReleaseGPUShader(gpu, fs);
    if (!gpu_pipeline)
    {
	fprintf(stderr, "I_GpuInit: pipeline: %s\n", SDL_GetError());
	return 0;
    }

    SDL_zero(smp);
    smp.min_filter = smp.mag_filter = SDL_GPU_FILTER_NEAREST;
    smp.mipmap_mode = SDL_GPU_SAMPLERMIPMAPMODE_NEAREST;
    smp.address_mode_u = smp.address_mode_v = smp.address_mode_w =
	SDL_GPU_SAMPLERADDRESSMODE_CLAMP_TO_EDGE;
    gpu_sampler_nn = SDL_CreateGPUSampler(gpu, &smp);
    smp.min_filter = smp.mag_filter = SDL_GPU_FILTER_LINEAR;
    gpu_sampler_ln = SDL_CreateGPUSampler(gpu, &smp);

    return gpu_pipeline && gpu_sampler_nn && gpu_sampler_ln;
}

//
// I_GpuCreateTexture
// (Re)create the streamed framebuffer texture + upload staging buffer at the
// current internal resolution.  Called from I_CreateTexture on the GPU path.
// The sampled texture is B8G8R8A8 to match the ARGB8888 (0xAARRGGBB) layout
// that I_ExpandFrame / the palette produce in little-endian memory.
//
static void I_GpuCreateTexture (void)
{
    SDL_GPUTextureCreateInfo		tci;
    SDL_GPUTransferBufferCreateInfo	tbi;

    if (gpu_tex)  { SDL_ReleaseGPUTexture(gpu, gpu_tex);  gpu_tex = NULL; }
    if (gpu_xfer) { SDL_ReleaseGPUTransferBuffer(gpu, gpu_xfer); gpu_xfer = NULL; }

    SDL_zero(tci);
    tci.type = SDL_GPU_TEXTURETYPE_2D;
    tci.format = SDL_GPU_TEXTUREFORMAT_B8G8R8A8_UNORM;
    tci.usage = SDL_GPU_TEXTUREUSAGE_SAMPLER;
    tci.width = SCREENWIDTH;	tci.height = SCREENHEIGHT;
    tci.layer_count_or_depth = 1;	tci.num_levels = 1;
    gpu_tex = SDL_CreateGPUTexture(gpu, &tci);

    SDL_zero(tbi);
    tbi.usage = SDL_GPU_TRANSFERBUFFERUSAGE_UPLOAD;
    tbi.size = SCREENWIDTH * SCREENHEIGHT * 4;
    gpu_xfer = SDL_CreateGPUTransferBuffer(gpu, &tbi);

    if (!gpu_tex || !gpu_xfer)
	I_Error("Could not create GPU framebuffer texture: %s", SDL_GetError());
}

//
// I_GpuPresent
// One frame on the SDL_GPU path: expand into the staging buffer, copy to the
// sampled texture, then draw the fullscreen triangle into the (letterboxed)
// swapchain.  Mirrors the renderer path's logical-presentation letterbox by
// centring a viewport of the target aspect inside the swapchain texture.
//
static void I_GpuPresent (void)
{
    SDL_GPUCommandBuffer*	cmd;
    SDL_GPUTexture*		swap;
    Uint32			sw, sh;
    void*			map;

    // 1) expand the frame (+ console overlay) into the upload staging buffer.
    map = SDL_MapGPUTransferBuffer(gpu, gpu_xfer, true);	// cycle: avoid stall
    if (map)
    {
	I_ExpandFrame(map, SCREENWIDTH*4);
	I_GpuDrawConsole((Uint32*)map);
	SDL_UnmapGPUTransferBuffer(gpu, gpu_xfer);
    }
    view_truecolor = 0;			// consumed; next frame must re-capture

    cmd = SDL_AcquireGPUCommandBuffer(gpu);
    if (!cmd)
	return;

    // 2) copy staging -> sampled texture.
    {
	SDL_GPUTextureTransferInfo	ti;
	SDL_GPUTextureRegion		reg;
	SDL_GPUCopyPass*		cp;

	SDL_zero(ti);
	ti.transfer_buffer = gpu_xfer;
	ti.pixels_per_row = SCREENWIDTH;	ti.rows_per_layer = SCREENHEIGHT;
	SDL_zero(reg);
	reg.texture = gpu_tex;
	reg.w = SCREENWIDTH;	reg.h = SCREENHEIGHT;	reg.d = 1;

	cp = SDL_BeginGPUCopyPass(cmd);
	SDL_UploadToGPUTexture(cp, &ti, &reg, true);	// cycle texture
	SDL_EndGPUCopyPass(cp);
    }

    // 3) draw the fullscreen triangle into the swapchain, letterboxed.
    if (!SDL_AcquireGPUSwapchainTexture(cmd, window, &swap, &sw, &sh) || !swap)
    {
	SDL_SubmitGPUCommandBuffer(cmd);	// minimised: upload only, nothing drawn
	return;
    }
    {
	SDL_GPUColorTargetInfo		cti;
	SDL_GPUViewport			vp;
	SDL_GPUTextureSamplerBinding	tsb;
	SDL_GPURenderPass*		rp;
	float	target_aspect = (float)SCREENWIDTH / (float)I_OutHeight();
	float	win_aspect = (float)sw / (float)sh;
	float	vw, vh;

	if (win_aspect > target_aspect) { vh = (float)sh; vw = sh * target_aspect; }
	else				{ vw = (float)sw; vh = sw / target_aspect; }

	SDL_zero(cti);
	cti.texture = swap;
	cti.load_op = SDL_GPU_LOADOP_CLEAR;	// black letterbox bars
	cti.store_op = SDL_GPU_STOREOP_STORE;
	cti.clear_color.a = 1.0f;
	rp = SDL_BeginGPURenderPass(cmd, &cti, 1, NULL);

	vp.x = (sw - vw) * 0.5f;	vp.y = (sh - vh) * 0.5f;
	vp.w = vw;	vp.h = vh;	vp.min_depth = 0.0f;	vp.max_depth = 1.0f;
	SDL_SetGPUViewport(rp, &vp);

	SDL_BindGPUGraphicsPipeline(rp, gpu_pipeline);
	tsb.texture = gpu_tex;
	tsb.sampler = mod_smooth ? gpu_sampler_ln : gpu_sampler_nn;
	SDL_BindGPUFragmentSamplers(rp, 0, &tsb, 1);
	SDL_DrawGPUPrimitives(rp, 3, 1, 0, 0);
	SDL_EndGPURenderPass(rp);
    }
    SDL_SubmitGPUCommandBuffer(cmd);
}

//
// I_DrawConsole
// MOD: draw the drop-down console's text with SDL3's built-in font
// (SDL_RenderDebugText, an 8x8 glyph set bundled in SDL3 -- no extra library or
// font file). C_Drawer has already dimmed the backdrop in the 8-bit framebuffer;
// this runs after the game frame is on the renderer and before present.
// Logical presentation is SCREENWIDTH x SCREENHEIGHT, so a render scale of
// `hires` lets us place text in 320x200 (BASE) coordinates and have it scale
// with the resolution, matching the old layout.
//
void I_DrawConsole (void)
{
    int		h, i;
    float	s;

    if (renderer == NULL)
	return;
    h = C_BaseHeight ();		// drop height in BASE rows, 0 = closed
    if (h <= 0)
	return;

    // Use a smaller, cleaner font scale so console text is compact, sharp,
    // and doesn't get oversized/blocky at high resolutions.
    s = (hires > 1) ? ((float)hires * 0.65f) : 0.75f;
    SDL_SetRenderScale (renderer, s, s);
    SDL_SetRenderDrawColor (renderer, 0xe0, 0xe0, 0xe0, 0xff);

    // Calculate positions in scaled render coordinates
    float inv_s = 1.0f / s;
    float base_scale = (float) hires;
    float x_pos = 6.0f * base_scale * inv_s;
    float y_pos = ((float)h - 9.0f) * base_scale * inv_s;
    float line_step = 8.0f * base_scale * inv_s;

    SDL_RenderDebugText (renderer, x_pos, y_pos, C_InputLine ());
    y_pos -= line_step;
    for (i = 0; i < C_ScrollCount () && y_pos > -10.0f; i++)
    {
	const char* line = C_ScrollLine (i);
	if (line && line[0])
	    SDL_RenderDebugText (renderer, x_pos, y_pos, line);
	y_pos -= line_step;
    }

    SDL_SetRenderScale (renderer, 1.0f, 1.0f);
}

//
// I_FinishUpdate
//
void I_FinishUpdate (void)
{
    // Track menu/console state: grab while playing, release in the menu.
    I_ApplyMouseGrab();

    static int	lasttic;
    int		tics;
    int		i;
    void*	pixels;
    int		pitch;

    // draws little dots on the bottom of the screen
    if (devparm)
    {

	i = I_GetTime();
	tics = i - lasttic;
	lasttic = i;
	if (tics > 20) tics = 20;

	for (i=0 ; i<tics*2 ; i+=2)
	    screens[0][ (SCREENHEIGHT-1)*SCREENWIDTH + i] = 0xff;
	for ( ; i<20*2 ; i+=2)
	    screens[0][ (SCREENHEIGHT-1)*SCREENWIDTH + i] = 0x0;
    }

    // SDL_GPU backend (-gpu): expand + stream + draw through the GPU pipeline.
    if (use_gpu)
    {
	I_GpuPresent();
	return;
    }

    // Expand the 8-bit palettized frame into the 32-bit streaming texture.
    // (Fullcolor compositing of the truecolor 3D view happens in I_ExpandFrame.)
    if ( !SDL_LockTexture(texture, NULL, &pixels, &pitch) )
	return;

    I_ExpandFrame(pixels, pitch);
    view_truecolor = 0;		// consumed; next frame must re-capture

    SDL_UnlockTexture(texture);

    SDL_RenderClear(renderer);
    SDL_RenderTexture(renderer, texture, NULL, NULL);
    I_DrawConsole();			// MOD: console text overlay (SDL3 font)
    SDL_RenderPresent(renderer);
}


